
package com.example.hms.dto;

import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;

/**
 * Project Name : Hospital Management System
 * Module       : Patient Management - DTO
 * Author       : Hemang
 * Date         : 09-11-2026
 *
 * Description:
 * Transfers patient information between the client and application.
 * Provides validation for incoming patient details.
 */

public record PatientDto(

        // Patient ID is generated by the database
        Long id,

        // Patient name must not be empty
        @NotBlank(message = "Patient name is required")
        @Size(max = 100, message = "Name cannot exceed 100 characters")
        String name,

        // Patient age must be between 0 and 120
        @NotNull(message = "Age is required")
        @Min(value = 0, message = "Age cannot be negative")
        @Max(value = 120, message = "Age cannot exceed 120")
        Integer age,

        // Gender must not be empty
        @NotBlank(message = "Gender is required")
        String gender,

        // Disease or medical condition must not be empty
        @NotBlank(message = "Disease is required")
        String disease,

        // Patient address must not be empty
        @NotBlank(message = "Address is required")
        String address,

        // Patient phone number must not be empty
        @NotBlank(message = "Phone number is required")
        @Size(max = 15, message = "Phone number cannot exceed 15 characters")
        String phoneNumber

) {
}

